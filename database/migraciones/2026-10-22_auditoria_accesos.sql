-- =====================================================================
-- Migración 2026-10-22: historial de inicios de sesión y permisos de
-- auditoría.
--
--   * Permisos nuevos "Ver inicios de sesión" y "Ver bitácora de cambios".
--     Nadie los recibe automáticamente: la cuenta principal ya tiene todos
--     los permisos y decide a quién más asignarlos.
--   * Tabla inicios_sesion: cada intento de ingreso con su resultado, IP y
--     navegador. Con RLS, sin acceso para la API de Supabase y con permisos
--     para dsi_app: los GRANT de rol_aplicacion.sql solo cubrieron las
--     tablas que existían entonces, y sin ellos fallarían el login y el
--     respaldo nocturno.
--   * Índice por fecha en logs_sistema para la bitácora de cambios.
--
-- Ejecutar UNA vez (Supabase → SQL Editor → pegar y "Run") ANTES de
-- publicar el código nuevo en el servidor. Se puede repetir sin daño.
-- =====================================================================

BEGIN;

SET LOCAL search_path TO inventario;

ALTER TABLE usuarios DROP CONSTRAINT IF EXISTS usuarios_permisos_validos;
ALTER TABLE usuarios ADD CONSTRAINT usuarios_permisos_validos CHECK (
    permisos <@ ARRAY[
        'EDITAR_EQUIPO', 'CREAR_USUARIO', 'EDITAR_USUARIO', 'CAMBIAR_CONTRASENA',
        'VER_INICIOS_SESION', 'VER_BITACORA'
    ]::text[]
);

CREATE TABLE IF NOT EXISTS inicios_sesion (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- NULL si el usuario escrito no existe. Lo escrito no se guarda: a
    -- veces es una contraseña tecleada en el campo equivocado.
    usuario_id integer REFERENCES usuarios (id) ON DELETE SET NULL,
    resultado  varchar(15) NOT NULL
               CHECK (resultado IN ('EXITOSO', 'CREDENCIALES', 'BLOQUEADO', 'DESACTIVADA')),
    ip         varchar(45) NOT NULL,
    navegador  varchar(255),
    fecha      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS inicios_sesion_fecha_idx ON inicios_sesion (fecha DESC);
CREATE INDEX IF NOT EXISTS inicios_sesion_usuario_idx ON inicios_sesion (usuario_id);
CREATE INDEX IF NOT EXISTS logs_sistema_fecha_idx ON logs_sistema (fecha DESC);

ALTER TABLE inicios_sesion ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
    rol_api text;
BEGIN
    FOREACH rol_api IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = rol_api) THEN
            EXECUTE format('REVOKE ALL ON TABLE inventario.inicios_sesion FROM %I', rol_api);
            EXECUTE format('REVOKE ALL ON SEQUENCE inventario.inicios_sesion_id_seq FROM %I', rol_api);
        END IF;
    END LOOP;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dsi_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON inventario.inicios_sesion TO dsi_app;
        GRANT USAGE, SELECT ON SEQUENCE inventario.inicios_sesion_id_seq TO dsi_app;

        IF NOT EXISTS (
            SELECT 1 FROM pg_policies
            WHERE schemaname = 'inventario' AND tablename = 'inicios_sesion' AND policyname = 'aplicacion_acceso_total'
        ) THEN
            CREATE POLICY aplicacion_acceso_total ON inventario.inicios_sesion
                FOR ALL TO dsi_app USING (true) WITH CHECK (true);
        END IF;
    END IF;
END
$$;

COMMIT;

-- Verificación: las cuatro filas deben decir "true".
SELECT 'Permisos nuevos aceptados' AS verificacion,
       (SELECT pg_get_constraintdef(oid) LIKE '%VER_BITACORA%' FROM pg_constraint
        WHERE conname = 'usuarios_permisos_validos' AND conrelid = 'inventario.usuarios'::regclass)::text AS resultado
UNION ALL
SELECT 'dsi_app puede registrar inicios de sesión',
       has_table_privilege('dsi_app', 'inventario.inicios_sesion', 'SELECT, INSERT')::text
UNION ALL
SELECT 'dsi_app puede usar la secuencia del id',
       has_sequence_privilege('dsi_app', 'inventario.inicios_sesion_id_seq', 'USAGE')::text
UNION ALL
SELECT 'Política RLS para dsi_app',
       EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'inventario' AND tablename = 'inicios_sesion')::text;
